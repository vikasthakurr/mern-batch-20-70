/**
 * HISTORY OF JAVASCRIPT (JS)
 *
 * 1. THE BIRTH (1995):
 *    - JavaScript was created by Brendan Eich in May 1995.
 *    - He was working at Netscape Communications at the time.
 *    - Believe it or not, the first version was written in just 10 DAYS!
 *
 * 2. THE NAMES:
 *    - Originally, it was called "Mocha".
 *    - Later, it was renamed to "LiveScript".
 *    - Finally, it was changed to "JavaScript" as a marketing tactic to ride the popularity of Java at the time,
 *      even though the two languages are very different.
 *
 * 3. STANDARDIZATION (ECMAScript):
 *    - To ensure different browsers could run JS the same way, Netscape submitted it to ECMA International.
 *    - This led to the "ECMAScript" standard (ES).
 *    - When people talk about "ES6", "ES2015", or "ESNext", they are talking about versions of this standard.
 *
 * 4. THE MODERN ERA:
 *    - 2009: ES5 was released (added 'use strict', JSON support, etc.).
 *    - 2015: ES6 (ECMAScript 2015) was a massive update that brought 'let', 'const', arrow functions, and classes.
 *    - Today: JavaScript is the most popular programming language in the world, used for:
 *      - Front-end (Websites)
 *      - Back-end (Node.js)
 *      - Mobile Apps (React Native)
 *      - Desktop Apps (Electron)
 *
 * 5. RECENT ECMASCRIPT ITERATIONS (2016‑2025):
 *    - ES2016 (2016): Array.prototype.includes, exponentiation operator (**).
 *    - ES2017 (2017): Async/Await, Object.entries/Object.values.
 *    - ES2018 (2018): Rest/Spread properties for objects, asynchronous iteration.
 *    - ES2019 (2019): Optional catch binding, Array.flat/flatMap, Object.fromEntries.
 *    - ES2020 (2020): Nullish coalescing (??), Optional chaining (?.), BigInt, globalThis.
 *    - ES2021 (2021): Logical assignment operators (&&=, ||=, ??=), String.replaceAll, Promise.any.
 *    - ES2022 (2022): Class fields, top‑level await, RegExp match indices.
 *    - ES2023 (2023): Array findLast & findLastIndex, change array toString behavior, new .at() method for typed arrays.
 *    - ES2024 (2024): Proposed additions – pattern matching, explicit resource management (using), refined .hasOwn() semantics.
 *    - ES2025 (2025): Upcoming features – private static class fields, improved error cause handling, temporal API enhancements.
 *
 * Fun Fact: JavaScript is often called the "Language of the Web" because every modern browser has a built‑in JS engine!
 */

